CREATE TABLE users
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(100) NOT NULL,
    email    VARCHAR(254) NOT NULL,
    password VARCHAR(255) NOT NULL,

    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_canonical CHECK (email = lower(trim(email)))
);

CREATE TABLE client
(
    user_id BIGINT PRIMARY KEY,
    card    VARCHAR(32) NOT NULL,

    CONSTRAINT fk_client_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE employee
(
    user_id    BIGINT PRIMARY KEY,
    department VARCHAR(100) NOT NULL,

    CONSTRAINT fk_employee_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE manufacturer
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,

    CONSTRAINT uq_manufacturer_name UNIQUE (name)
);

CREATE TABLE appliance
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(150)   NOT NULL,
    category        VARCHAR(20)    NOT NULL,
    model           VARCHAR(100)   NOT NULL,
    manufacturer_id BIGINT         NOT NULL,
    power_type      VARCHAR(20)    NOT NULL,
    characteristic  VARCHAR(1000)  NOT NULL,
    description     VARCHAR(4000)  NOT NULL,
    power           INTEGER        NOT NULL,
    price           NUMERIC(14, 2) NOT NULL,

    CONSTRAINT fk_appliance_manufacturer
        FOREIGN KEY (manufacturer_id) REFERENCES manufacturer (id),

    CONSTRAINT ck_appliance_category
        CHECK (category IN ('BIG', 'SMALL')),

    CONSTRAINT ck_appliance_power_type
        CHECK (power_type IN ('AC220', 'AC110', 'ACCUMULATOR')),

    CONSTRAINT ck_appliance_power
        CHECK (power > 0),

    CONSTRAINT ck_appliance_price
        CHECK (price > 0)
);

CREATE TABLE orders
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT,
    client_id   BIGINT  NOT NULL,
    approved    BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_orders_employee
        FOREIGN KEY (employee_id) REFERENCES employee (user_id),

    CONSTRAINT fk_orders_client
        FOREIGN KEY (client_id) REFERENCES client (user_id)
);

CREATE TABLE order_row
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appliance_id BIGINT         NOT NULL,
    orders_id    BIGINT,
    number       BIGINT         NOT NULL,
    amount       NUMERIC(19, 2) NOT NULL,

    CONSTRAINT fk_order_row_appliance
        FOREIGN KEY (appliance_id) REFERENCES appliance (id),

    CONSTRAINT fk_order_row_order
        FOREIGN KEY (orders_id) REFERENCES orders (id),

    CONSTRAINT ck_order_row_number
        CHECK (number > 0),

    CONSTRAINT ck_order_row_amount
        CHECK (amount > 0)
);
