CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    replaced_by BIGINT,
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_refresh_token_replacement FOREIGN KEY (replaced_by) REFERENCES refresh_token(id) ON DELETE SET NULL,
    CONSTRAINT ck_refresh_token_hash CHECK (CHAR_LENGTH(token_hash) = 64)
);
CREATE INDEX ix_refresh_token_user ON refresh_token(user_id);
CREATE INDEX ix_refresh_token_expiry ON refresh_token(expires_at);
CREATE INDEX ix_refresh_token_replacement ON refresh_token(replaced_by);
